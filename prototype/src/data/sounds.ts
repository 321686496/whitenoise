/**
 * 声栖 · 内置白噪音音频库
 *
 * 全量声音数据集中管理，供首页、音频库页、发现页等多处复用。
 * iconName 需与 components/Icon.vue 中已定义的图标名保持一致。
 */

/* ------------------------------------------------------------------------- *
 * 类型定义
 * ------------------------------------------------------------------------- */

export interface Sound {
  id: string
  name: string
  type: string // 显示分类：合成白噪音 / 自然音 / 城市音 / 环境音
  category: string // 筛选分类 key：synthetic / nature / urban / ambient
  iconName: string // 对应 Icon.vue 的图标名
  color: string // 莫兰迪色系
  gradient: string // 封面渐变色
  duration: string // 音频时长，如 "30:00"
  sampleRate: string // 采样率，如 "44.1kHz"
  quality: string // 音质标签，如 "无损" / "高清"
  source: string // 声音来源/采集说明
  desc: string // 30字左右声音描述
  scenes: string[] // 适用场景标签，如 ['助眠','专注','冥想']
  loopLength: string // 循环片段长度，如 "2min"
}

export interface FeaturedScene {
  id: string
  name: string
  desc: string
  iconName: string
  gradient: string
  tags: string[] // 场景标签，如 ['助眠','深度睡眠']
  soundIds: string[] // 声音组合
  ratio: number[] // 每个声音的比例
  playCount: string // 播放量，如 "12.6万"
  duration: string
}

export interface FeaturedSound extends Sound {
  hot: number // 热度值
}

